-- ============================================================
-- Vue pour le reporting
-- ============================================================

CREATE OR REPLACE VIEW COPT.V_DOSSIERS_ATCT_ACTIFS AS
SELECT 
    d.ATCT_ID,
    d.NUM_SECU_SOCIALE,
    d.NOM_FR || ' ' || d.PRENOM_FR AS NOM_COMPLET_FR,
    d.NOM_AR || ' ' || d.PRENOM_AR AS NOM_COMPLET_AR,
    d.EMAIL,
    d.TELEPHONE,
    d.PAYS_ETRANGER,
    d.DATE_DEBUT_DETACHEMENT,
    d.DATE_FIN_DETACHEMENT,
    d.SALAIRE_TUNISIE,
    d.CODE_REGIME,
    d.MODE_PAIEMENT,
    d.STATUT,
    d.DATE_CREATION,
    d.EMAIL_ENVOYE,
    d.NUM_AFFILIATION
FROM COPT.DOSSIER_ATCT d
WHERE d.ACTIF = TRUE
ORDER BY d.DATE_CREATION DESC;

COMMENT ON VIEW COPT.V_DOSSIERS_ATCT_ACTIFS IS 'Vue des dossiers ATCT actifs pour le reporting';
